-- Схема базы данных «Прогулки с Катюшей». Выполните целиком в Supabase → SQL Editor.

create table if not exists public.places (
  id          bigint generated by default as identity primary key,
  title       text not null,
  description text,
  category    text not null,                       -- slug: spa, capybara, hookah, gaming, city, garden, trips, sea, resort
  latitude    double precision not null check (latitude  between -90  and 90),
  longitude   double precision not null check (longitude between -180 and 180),
  image       text,                                -- публичная ссылка на фото
  rating      numeric(2,1) check (rating between 0 and 5),
  is_approx   boolean not null default false,      -- true, пока точные координаты не проверены
  region      text,                                -- значение фильтра: страна/город/регион
  city        text,                                -- населённый пункт внутри выбранного региона
  address     text,
  price_min   numeric(12,2) check (price_min is null or price_min >= 0),
  price_max   numeric(12,2) check (price_max is null or price_max >= 0),
  price_unit  text,                                -- AZN, RUB, GEL или подпись бесплатного входа
  review_count integer check (review_count is null or review_count >= 0),
  opening_hours text,
  phone       text,
  map_url     text,
  source_urls text[] not null default '{}',
  created_at  timestamptz not null default now()
);

-- Безопасное расширение уже созданной таблицы: имеющиеся места не удаляются и не заменяются.
alter table public.places add column if not exists region text;
alter table public.places add column if not exists city text;
alter table public.places add column if not exists address text;
alter table public.places add column if not exists price_min numeric(12,2);
alter table public.places add column if not exists price_max numeric(12,2);
alter table public.places add column if not exists price_unit text;
alter table public.places add column if not exists review_count integer;
alter table public.places add column if not exists opening_hours text;
alter table public.places add column if not exists phone text;
alter table public.places add column if not exists map_url text;
alter table public.places add column if not exists source_urls text[] not null default '{}';

create table if not exists public.routes (
  id          bigint generated by default as identity primary key,
  title       text not null,
  description text,
  places      bigint[] not null default '{}',     -- id мест по порядку остановок
  created_at  timestamptz not null default now()
);

create table if not exists public.favorites (
  id          bigint generated by default as identity primary key,
  place_id    bigint not null references public.places(id) on delete cascade,
  created_at  timestamptz not null default now(),
  unique (place_id)
);

create index if not exists places_category_idx on public.places (category);
create index if not exists places_region_idx on public.places (region);
create index if not exists places_region_category_idx on public.places (region, category);
create index if not exists places_rating_idx on public.places (rating);

-- Row Level Security
alter table public.places    enable row level security;
alter table public.routes    enable row level security;
alter table public.favorites enable row level security;

-- Читать каталог и маршруты может любой посетитель сайта.
create policy "places read" on public.places for select to anon, authenticated using (true);
create policy "routes read" on public.routes for select to anon, authenticated using (true);

-- Избранное хранится локально в браузере. Таблица favorites закрыта от публичного API.
create policy "favorites deny public access" on public.favorites as restrictive
  for all to anon, authenticated using (false) with check (false);
-- Для будущей синхронизации между устройствами потребуется авторизованный профиль и user_id.

-- Доступ к Data API выдаётся явно. RLS выше определяет, какие строки доступны.
grant usage on schema public to anon, authenticated, service_role;
grant select on table public.places, public.routes to anon, authenticated;
grant all privileges on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to service_role;

