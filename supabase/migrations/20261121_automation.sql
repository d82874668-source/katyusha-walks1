-- Автоматизация каталога. Только ДОБАВЛЯЕТ поля и таблицы. Ничего не удаляет.
-- Выполните в Supabase → SQL Editor после 20261120_expand_places.sql.
begin;

-- 1. Новые поля существующей таблицы places (отдельную таблицу venues не создаём: каталог уже живёт в places)
alter table public.places add column if not exists slug text;
alter table public.places add column if not exists website text;
alter table public.places add column if not exists social_links jsonb not null default '{}'::jsonb;
alter table public.places add column if not exists status text not null default 'active';
alter table public.places add column if not exists coord_source text;          -- откуда взяты координаты
alter table public.places add column if not exists discovered_at timestamptz not null default now();
alter table public.places add column if not exists updated_at timestamptz not null default now();
alter table public.places add column if not exists last_verified_at timestamptz;
do $$ begin
  alter table public.places add constraint places_status_chk check (status in ('active','closed','needs_review'));
exception when duplicate_object then null; end $$;
create index if not exists places_status_idx on public.places (status);
create index if not exists places_geo_idx on public.places (latitude, longitude);

-- 2. Администраторы (только они управляют синхронизацией)
create table if not exists public.admin_users (user_id uuid primary key references auth.users(id) on delete cascade, created_at timestamptz not null default now());
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path = public as
$$ select exists (select 1 from public.admin_users where user_id = auth.uid()) $$;

-- 3. Источники и журналы
create table if not exists public.data_sources (
  id bigint generated by default as identity primary key, name text not null unique, source_type text not null,
  enabled boolean not null default false, last_sync_at timestamptz, status text not null default 'idle', notes text);
create table if not exists public.sync_logs (
  id bigint generated by default as identity primary key, source_id bigint references public.data_sources(id),
  action text, started_at timestamptz not null default now(), finished_at timestamptz, status text not null default 'running',
  found_count int not null default 0, added_count int not null default 0, updated_count int not null default 0,
  duplicate_count int not null default 0, error_count int not null default 0, error_details text);

-- 4. Внешние ID, рейтинги по источникам (не смешиваются), фото, история, очередь проверки
create table if not exists public.place_external_ids (
  id bigint generated by default as identity primary key, place_id bigint not null references public.places(id) on delete cascade,
  source_id bigint not null references public.data_sources(id), external_id text not null, fetched_at timestamptz not null default now(),
  unique (source_id, external_id));
create table if not exists public.place_ratings (
  id bigint generated by default as identity primary key, place_id bigint not null references public.places(id) on delete cascade,
  source_id bigint not null references public.data_sources(id), rating numeric(2,1) check (rating between 0 and 5),
  review_count int, fetched_at timestamptz not null default now(), unique (place_id, source_id));
create table if not exists public.place_photos (
  id bigint generated by default as identity primary key, place_id bigint not null references public.places(id) on delete cascade,
  url text not null, license text not null, attribution text, created_at timestamptz not null default now(), unique (place_id, url));
create table if not exists public.place_history (
  id bigint generated by default as identity primary key, place_id bigint references public.places(id) on delete set null,
  changed_at timestamptz not null default now(), field text, old_value text, new_value text, source text);
create table if not exists public.place_review_queue (
  id bigint generated by default as identity primary key, source_id bigint references public.data_sources(id),
  candidate jsonb not null, matched_place_id bigint references public.places(id) on delete set null, reason text,
  state text not null default 'pending' check (state in ('pending','approved','rejected')), created_at timestamptz not null default now());

insert into public.data_sources (name, source_type, enabled, notes) values
  ('osm_overpass','open_data', true,  'OpenStreetMap, лицензия ODbL, нужна ссылка на источник'),
  ('google_places','paid_api', false, 'Не подключён: платный, ограничения на хранение данных'),
  ('foursquare','api', false,         'Не подключён: нужен ключ, проверьте условия хранения'),
  ('geoapify','api', false,           'Не подключён: нужен ключ')
on conflict (name) do nothing;

-- 5. RLS. Посетители только читают каталог; всё остальное только администратор.
alter table public.admin_users enable row level security;
alter table public.data_sources enable row level security;
alter table public.sync_logs enable row level security;
alter table public.place_external_ids enable row level security;
alter table public.place_ratings enable row level security;
alter table public.place_photos enable row level security;
alter table public.place_history enable row level security;
alter table public.place_review_queue enable row level security;

drop policy if exists "ratings read" on public.place_ratings;
create policy "ratings read" on public.place_ratings for select using (true);
drop policy if exists "photos read" on public.place_photos;
create policy "photos read" on public.place_photos for select using (true);
drop policy if exists "admin sources" on public.data_sources;
create policy "admin sources" on public.data_sources for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admin logs" on public.sync_logs;
create policy "admin logs" on public.sync_logs for select to authenticated using (public.is_admin());
drop policy if exists "admin ext" on public.place_external_ids;
create policy "admin ext" on public.place_external_ids for select to authenticated using (public.is_admin());
drop policy if exists "admin history" on public.place_history;
create policy "admin history" on public.place_history for select to authenticated using (public.is_admin());
drop policy if exists "admin queue" on public.place_review_queue;
create policy "admin queue" on public.place_review_queue for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admin self" on public.admin_users;
create policy "admin self" on public.admin_users for select to authenticated using (user_id = auth.uid());
-- Запись в sync_logs, place_*, places из функции идёт через service_role и RLS обходит.

commit;

-- Исправление: у части мест Нижнего Тагила в поле image были личные фото людей (2ГИС "profile" и файлы 55-59.jpg).
-- Скрываем их; у карточек появится аккуратная заглушка. Строки мест не удаляются.
update public.places set image = null
where image like '%photo.2gis.com/images/profile%' or image ~ '/places/5[5-9][.]jpg$';
